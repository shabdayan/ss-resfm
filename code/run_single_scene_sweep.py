#!/usr/bin/env python
"""
Single-scene comparison sweep: ESFM (Moran et al., ICCV 2021, official repo) vs.
U-ESFM (this repo) on the Olsson dataset, calibrated (Euclidean) setting.
Implements Phase 1 of SPEC_single_scene_experiments.md.

Fairness ground rules enforced here:
  * identical inputs: both methods read the same shared datasets/Euclidean/<scene>.npz
    (symlinked into both repos from u-esfm/datasets/Euclidean);
  * identical post-processing: BOTH methods run WITHOUT bundle adjustment
    (ba.run_ba = false); a shared BA can be applied later by evaluate_single_scene.py
    to both methods' raw cameras, and is reported separately;
  * identical budgets: same epochs / eval intervals / lr schedule for both methods;
  * sequential execution: runs never share a GPU (one subprocess at a time per worker);
    for each (scene, seed) the two methods run back-to-back on the same GPU;
  * seeds: each (method, scene, seed) is a separate run with the seed in the conf.

Layout (all under --results-root, default <this repo>/code/results/single_scene):
  <method>/<scene_slug>/seed<k>/
      log.txt           full stdout+stderr of the run
      run.conf          exact config used
      run_meta.json     status, timing, command line, host/GPU
      raw/              the method's own outputs (metrics xlsx, cameras npz, ...)

Resumable: a run whose run_meta.json says status=completed and whose cameras npz
exists is skipped. Fail-soft: a crashed run is recorded and the sweep continues.
"""
